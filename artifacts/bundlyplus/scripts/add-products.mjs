function run() {
  const raw = readFileSync(PRODUCTS_PATH, 'utf8');
  const existing = JSON.parse(raw);
  const ids = new Set(existing.map((p) => p.id));
  let added = 0;
  let skipped = 0;

  for (const p of NEW_PRODUCTS) {
    if (ids.has(p.id)) {
      skipped++;
      continue;
    }
    existing.push({
      id: p.id,
      name: p.name,
      price: p.price,
      description: p.description,
      category: p.category,
      duration: p.duration,
      account_type: p.account_type,
      features: p.features,
      image_url: '',
      created_at: now + added,
      hot: !!p.hot,
      featured: !!p.featured,
    });
    ids.add(p.id);
    added++;
  }

  writeFileSync(PRODUCTS_PATH, JSON.stringify(existing, null, 2) + '\n');
  console.log(`added ${added} new products, skipped ${skipped} (already existed)`);
  console.log(`total products now: ${existing.length}`);
}

run();
